const assert=require('node:assert/strict');
const P=require('../docs/public-engine.js');
const R=require('../docs/engine.js');
const point=(day,value,metric='wiki_pageviews')=>({observed_date:'2026-01-'+String(day).padStart(2,'0'),platform:metric==='wiki_pageviews'?'维基百科':'GitHub',keyword:'功能测试',opportunity_type:'软件',metric_type:metric,metric_value:value,source_type:'public_api',source_name:'测试',source_scope:'固定范围',source_url:'https://example.org/',notes:'',is_demo:0});
const wiki=Array.from({length:14},(_,i)=>point(i+1,i<7?10:20));
let result=P.analyze(wiki,'wiki_pageviews','2026-01-15').candidates[0];
assert.equal(result.median_change_pct,100);
assert.equal(result.rankable,true);
assert.equal(result.current_value,20);
assert.equal(result.status,'阅读关注上升');
assert.equal(P.analyze(wiki.slice(4),'wiki_pageviews','2026-01-15').candidates[0].rankable,false);
assert.equal(P.analyze(wiki,'wiki_pageviews','2026-01-20').candidates[0].rankable,false);
assert.equal(P.analyze(wiki,'wiki_pageviews','2026-01-15',[{keyword:'功能测试',opportunity_type:'软件',provider:'wikipedia',status:'error'}]).candidates[0].rankable,false);
assert.equal(P.analyze(wiki.map((r,i)=>({...r,metric_value:i<7?0:20})),'wiki_pageviews','2026-01-15').candidates[0].median_change_pct,null);
let stars=[point(1,100,'github_stars')];
assert.equal(P.analyze(stars,'github_stars','2026-01-01').candidates[0].median_change_pct,null);
stars.push(point(7,110,'github_stars'),point(8,115,'github_stars'));
result=P.analyze(stars,'github_stars','2026-01-08').candidates[0];
assert.ok(Math.abs(result.median_change_pct-15)<1e-8);
assert.equal(result.net_change,5);
assert.equal(P.analyze([stars[0],stars[2]],'github_stars','2026-01-08').candidates[0].net_change,null);
assert.equal(P.analyze([...wiki,...stars],'wiki_pageviews','2026-01-15').candidates.length,1);
assert.equal(R.validate(wiki[0]).source_type,'public_api');
console.log('PASS: public metric isolation, date coverage, zero baseline, stale sources and honest Star history.');
